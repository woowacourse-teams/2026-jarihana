BEGIN;
CREATE TABLE sparring_topic (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    title varchar(80) NOT NULL,
    claim_a varchar(32) NOT NULL,
    claim_b varchar(32) NOT NULL,
    description varchar(240) NOT NULL,
    revision bigint NOT NULL,
    creator_id bigint NOT NULL REFERENCES member(id),
    CONSTRAINT ck_sparring_revision CHECK (revision > 0)
);
CREATE TABLE sparring_vote (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    topic_id bigint NOT NULL REFERENCES sparring_topic(id),
    member_id bigint NOT NULL REFERENCES member(id),
    side varchar(8) NOT NULL CHECK (side IN ('MINT', 'CORAL')),
    CONSTRAINT uk_sparring_vote_member UNIQUE (topic_id, member_id)
);
CREATE TABLE sparring_post (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    topic_id bigint NOT NULL REFERENCES sparring_topic(id),
    member_id bigint NOT NULL REFERENCES member(id),
    side varchar(8) NOT NULL CHECK (side IN ('MINT', 'CORAL')),
    text varchar(160) NOT NULL,
    request_id uuid NOT NULL,
    reply_to_id bigint REFERENCES sparring_post(id),
    CONSTRAINT uk_sparring_post_request UNIQUE (topic_id, member_id, request_id)
);
CREATE INDEX idx_sparring_post_topic_id ON sparring_post(topic_id, id);
CREATE INDEX idx_sparring_topic_created_id ON sparring_topic(created_at DESC, id DESC);
COMMIT;
