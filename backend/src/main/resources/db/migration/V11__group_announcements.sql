-- 모임 공지와 공지 등록 알림을 저장한다.
SET LOCAL lock_timeout = '5s';

CREATE TABLE announcements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL,
    author_member_id bigint NOT NULL,
    title character varying(100) NOT NULL,
    content character varying(10000) NOT NULL,
    scope character varying(20) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT ck_announcements_title CHECK (char_length(trim(title)) BETWEEN 1 AND 100),
    CONSTRAINT ck_announcements_content CHECK (char_length(trim(content)) BETWEEN 1 AND 10000),
    CONSTRAINT ck_announcements_scope CHECK (scope IN ('MEMBERS', 'PUBLIC')),
    CONSTRAINT fk_announcements_group FOREIGN KEY (group_id) REFERENCES groups(id) ON DELETE CASCADE,
    CONSTRAINT fk_announcements_author FOREIGN KEY (author_member_id) REFERENCES member(id)
);

CREATE INDEX idx_announcements_group_created_id
    ON announcements (group_id, created_at DESC, id DESC);

ALTER TABLE notifications ADD CONSTRAINT ck_notifications_event_type_v8 CHECK (
    event_type IN ('GROUP_CREATED', 'REGISTRATION_SUBMITTED', 'PARTICIPANT_JOINED', 'REGISTRATION_APPROVED',
                   'REGISTRATION_REJECTED', 'REGISTRATION_SYSTEM_REJECTED', 'INVITATION_RECEIVED',
                   'ACTIVITY_POST_COMMENTED', 'ACTIVITY_POST_REACTED', 'GROUP_ANNOUNCEMENT_CREATED')
) NOT VALID;

-- 기존 제약이 과거 행을 검증했으므로 재검증 테이블 스캔은 생략하고 새 쓰기만 검사한다.
ALTER TABLE notifications DROP CONSTRAINT ck_notifications_event_type;
ALTER TABLE notifications RENAME CONSTRAINT ck_notifications_event_type_v8 TO ck_notifications_event_type;
