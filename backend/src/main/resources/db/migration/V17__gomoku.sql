CREATE TABLE gomoku_room (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    host_member_id bigint NOT NULL REFERENCES member(id),
    host_name varchar(50) NOT NULL,
    guest_member_id bigint REFERENCES member(id),
    guest_name varchar(50),
    visibility varchar(16) NOT NULL CHECK (visibility IN ('PUBLIC','PRIVATE')),
    rule varchar(16) NOT NULL CHECK (rule IN ('RENJU','FREESTYLE')),
    status varchar(16) NOT NULL CHECK (status IN ('WAITING','PLAYING','FINISHED','CLOSED')),
    host_ready boolean NOT NULL,
    guest_ready boolean NOT NULL,
    game_number integer NOT NULL,
    black_member_id bigint NOT NULL,
    board varchar(225) NOT NULL CHECK (board ~ '^[012]{225}$'),
    ply integer NOT NULL CHECK (ply BETWEEN 0 AND 225),
    last_x integer,
    last_y integer,
    winner_member_id bigint REFERENCES member(id),
    end_reason varchar(16),
    turn_deadline timestamp(6),
    revision bigint NOT NULL CHECK (revision > 0),
    touched_at timestamp(6) NOT NULL,
    invite_hash varchar(64),
    CHECK (guest_member_id IS NULL OR guest_member_id <> host_member_id)
);
CREATE INDEX idx_gomoku_lobby ON gomoku_room(created_at DESC,id DESC) WHERE status='WAITING' AND visibility='PUBLIC';
CREATE INDEX idx_gomoku_expiry ON gomoku_room(turn_deadline) WHERE status='PLAYING';
CREATE INDEX idx_gomoku_idle ON gomoku_room(touched_at) WHERE status IN ('WAITING','FINISHED');
CREATE INDEX idx_gomoku_invite ON gomoku_room(invite_hash) WHERE invite_hash IS NOT NULL;

-- A seat is a temporary membership claim. Leaving/closing releases the claim; room history remains.
CREATE TABLE gomoku_seat (
    member_id bigint PRIMARY KEY REFERENCES member(id),
    room_id bigint NOT NULL REFERENCES gomoku_room(id)
);
CREATE INDEX idx_gomoku_seat_room ON gomoku_seat(room_id);

CREATE TABLE gomoku_move (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    room_id bigint NOT NULL REFERENCES gomoku_room(id),
    game_number integer NOT NULL,
    member_id bigint NOT NULL REFERENCES member(id),
    ply integer NOT NULL,
    x integer NOT NULL CHECK (x BETWEEN 0 AND 14),
    y integer NOT NULL CHECK (y BETWEEN 0 AND 14),
    request_id uuid NOT NULL,
    UNIQUE(room_id,game_number,ply),
    UNIQUE(room_id,game_number,member_id,request_id)
);
