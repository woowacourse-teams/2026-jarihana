CREATE TABLE member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_name VARCHAR(4) NOT NULL,
    generation INTEGER,
    member_type VARCHAR(20) NOT NULL,
    github_id VARCHAR(50) NOT NULL,
    course VARCHAR(20),
    withdrawn_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_member_github_id UNIQUE (github_id),
    CONSTRAINT uk_member_crew_name_generation UNIQUE (crew_name, generation),
    CONSTRAINT ck_member_profile_fields CHECK (
        (member_type = 'COACH' AND course IS NULL AND generation IS NULL)
        OR (member_type = 'CREW' AND course IS NOT NULL AND generation > 0)
    )
);
CREATE UNIQUE INDEX uk_member_coach_name ON member (crew_name) WHERE member_type = 'COACH';

