    CONSTRAINT ck_invitation_status CHECK (((((status)::text = 'VALID'::text) AND (revoked_at IS NULL)) OR (((status)::text = 'REJECTED'::text) AND ((type)::text = 'DIRECT'::text)) OR (((status)::text = 'CANCELED'::text) AND (revoked_at IS NOT NULL)))),
    CONSTRAINT ck_invitation_type CHECK (((((type)::text = 'DIRECT'::text) AND (target_member_id IS NOT NULL) AND (target_member_id <> inviter_member_id) AND (expires_at IS NULL) AND (token_hash IS NULL) AND (encrypted_token IS NULL)) OR (((type)::text = 'LINK'::text) AND (target_member_id IS NULL) AND (expires_at IS NOT NULL) AND (expires_at > created_at) AND (token_hash IS NOT NULL) AND ((token_hash)::text ~ '^[0-9a-f]{64}$'::text) AND (encrypted_token IS NOT NULL) AND (length(TRIM(BOTH FROM encrypted_token)) > 0))))
