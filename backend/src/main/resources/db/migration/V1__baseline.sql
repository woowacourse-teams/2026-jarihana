    updated_at timestamp without time zone NOT NULL,
    CONSTRAINT ck_notification_deliveries_state CHECK (((subscription_generation > 0) AND ((attempt_count >= 0) AND (attempt_count <= 5)) AND (expires_at > created_at) AND ((((status)::text = 'IN_FLIGHT'::text) AND (lease_token IS NOT NULL) AND (locked_until IS NOT NULL)) OR (((status)::text <> 'IN_FLIGHT'::text) AND (lease_token IS NULL) AND (locked_until IS NULL))) AND ((((status)::text = 'ACCEPTED'::text) AND (accepted_at IS NOT NULL)) OR (((status)::text <> 'ACCEPTED'::text) AND (accepted_at IS NULL))) AND ((((status)::text = 'PENDING'::text) AND (attempt_count = 0)) OR (((status)::text = ANY ((ARRAY['IN_FLIGHT'::character varying, 'ACCEPTED'::character varying])::text[])) AND (attempt_count >= 1)) OR (((status)::text = 'RETRY'::text) AND ((attempt_count >= 1) AND (attempt_count <= 4))) OR ((status)::text = ANY ((ARRAY['FAILED'::character varying, 'CANCELLED'::character varying])::text[]))))),
    CONSTRAINT ck_notification_deliveries_status CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'IN_FLIGHT'::character varying, 'RETRY'::character varying, 'ACCEPTED'::character varying, 'FAILED'::character varying, 'CANCELLED'::character varying])::text[])))
