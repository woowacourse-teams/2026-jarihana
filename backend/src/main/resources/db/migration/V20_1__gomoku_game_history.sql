CREATE TABLE gomoku_game (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    room_id bigint NOT NULL REFERENCES gomoku_room(id),
    game_number integer NOT NULL CHECK (game_number > 0),
    host_member_id bigint NOT NULL REFERENCES member(id),
    guest_member_id bigint NOT NULL REFERENCES member(id),
    host_name varchar(50) NOT NULL,
    guest_name varchar(50) NOT NULL,
    black_member_id bigint NOT NULL REFERENCES member(id),
    rule varchar(16) NOT NULL CHECK (rule IN ('RENJU','FREESTYLE')),
    winner_member_id bigint REFERENCES member(id),
    end_reason varchar(16) CHECK (end_reason IN ('FIVE','DRAW','RESIGN','TIMEOUT')),
    ply integer NOT NULL CHECK (ply BETWEEN 0 AND 225),
    ended_at timestamp(6),
    UNIQUE (room_id, game_number),
    CHECK (host_member_id <> guest_member_id),
    CHECK (black_member_id IN (host_member_id, guest_member_id)),
    CHECK (winner_member_id IS NULL OR winner_member_id IN (host_member_id, guest_member_id)),
    CHECK ((ended_at IS NULL AND end_reason IS NULL AND winner_member_id IS NULL)
        OR (ended_at IS NOT NULL AND end_reason IS NOT NULL
            AND ((end_reason = 'DRAW' AND winner_member_id IS NULL)
                OR (end_reason <> 'DRAW' AND winner_member_id IS NOT NULL))))
);
CREATE INDEX idx_gomoku_game_host ON gomoku_game(host_member_id, ended_at DESC, id DESC) WHERE ended_at IS NOT NULL;
CREATE INDEX idx_gomoku_game_guest ON gomoku_game(guest_member_id, ended_at DESC, id DESC) WHERE ended_at IS NOT NULL;
