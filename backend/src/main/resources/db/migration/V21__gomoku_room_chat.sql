ALTER TABLE gomoku_seat
    ADD COLUMN chat_start_sequence bigint NOT NULL DEFAULT 0 CHECK (chat_start_sequence >= 0),
    ADD COLUMN participation_id uuid NOT NULL DEFAULT gen_random_uuid();

CREATE TABLE gomoku_chat_room (
    room_id bigint PRIMARY KEY REFERENCES gomoku_room(id) ON DELETE CASCADE,
    last_sequence bigint NOT NULL DEFAULT 0 CHECK (last_sequence >= 0)
);
INSERT INTO gomoku_chat_room(room_id) SELECT id FROM gomoku_room;

CREATE TABLE gomoku_chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL REFERENCES gomoku_chat_room(room_id) ON DELETE CASCADE,
    sequence bigint NOT NULL CHECK (sequence > 0),
    sender_id bigint NOT NULL REFERENCES member(id),
    participation_id uuid NOT NULL,
    client_message_id uuid NOT NULL,
    author varchar(50) NOT NULL,
    content text NOT NULL,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    UNIQUE(room_id, sequence),
    UNIQUE(room_id, participation_id, client_message_id)
);
