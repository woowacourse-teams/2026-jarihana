CREATE TABLE gomoku_observation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    room_id bigint NOT NULL REFERENCES gomoku_room(id),
    member_id bigint NOT NULL REFERENCES member(id),
    request_id uuid NOT NULL,
    participation_id uuid NOT NULL UNIQUE,
    chat_start_sequence bigint NOT NULL CHECK (chat_start_sequence >= 0),
    left_at timestamp(6),
    UNIQUE (room_id, member_id, request_id)
);
CREATE INDEX idx_gomoku_observation_active ON gomoku_observation(room_id, participation_id) WHERE left_at IS NULL;

CREATE TABLE gomoku_observer_connection (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    observation_id bigint NOT NULL REFERENCES gomoku_observation(id),
    connection_id uuid NOT NULL UNIQUE,
    expires_at timestamp(6) NOT NULL
);
CREATE INDEX idx_gomoku_observer_connection_active ON gomoku_observer_connection(observation_id, expires_at);
CREATE INDEX idx_gomoku_observer_connection_expiry ON gomoku_observer_connection(expires_at);

ALTER TABLE gomoku_chat_message ADD COLUMN sender_role varchar(16) NOT NULL DEFAULT 'PARTICIPANT'
    CHECK (sender_role IN ('PARTICIPANT', 'SPECTATOR'));
