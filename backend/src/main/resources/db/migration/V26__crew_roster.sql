-- 우테코 크루 명단. 이 명단에 있는 GitHub 계정만 크루가 된다.
-- 저장소가 공개라 명단 데이터는 여기에 두지 않고 운영자가 backend/db/operations/crew-roster-import.sql로 넣는다.
-- 크루 인증 코드보다 먼저 배포해, 인증이 시작되기 전에 운영자가 명단을 미리 적재할 수 있게 한다.
-- 크루 인증에 필요한 값만 저장하고 크루 닉네임과 GitHub 로그인 이름은 저장하지 않는다.
CREATE TABLE crew_roster (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_id character varying(50) NOT NULL,
    generation integer NOT NULL,
    course character varying(20) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL DEFAULT localtimestamp,
    updated_at timestamp(6) without time zone NOT NULL DEFAULT localtimestamp,
    CONSTRAINT uk_crew_roster_github_id UNIQUE (github_id),
    CONSTRAINT ck_crew_roster_generation CHECK (generation > 0),
    CONSTRAINT ck_crew_roster_course CHECK (
        (course)::text = ANY (ARRAY['BACKEND'::text, 'FRONTEND'::text, 'ANDROID'::text])
    )
);
