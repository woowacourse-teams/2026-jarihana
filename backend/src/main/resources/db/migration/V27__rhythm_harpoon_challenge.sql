CREATE TABLE rhythm_challenge (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    member_id bigint NOT NULL REFERENCES member(id),
    level varchar(16) NOT NULL CHECK (level IN ('EASY', 'MEDIUM', 'HARD', 'HARDEST')),
    scroll_speed double precision NOT NULL CHECK (scroll_speed >= 1 AND scroll_speed <= 3),
    seed integer NOT NULL,
    rules_version varchar(40) NOT NULL,
    chart_version varchar(40) NOT NULL,
    status varchar(16) NOT NULL CHECK (status IN ('CREATED', 'PLAYING', 'FINISHED', 'INVALID')),
    started_at timestamp(6),
    last_batch_at timestamp(6),
    last_sequence integer NOT NULL DEFAULT 0 CHECK (last_sequence >= 0),
    played_until double precision NOT NULL DEFAULT 0,
    last_input_at double precision,
    score bigint NOT NULL DEFAULT 0,
    perfect_count integer NOT NULL DEFAULT 0,
    hit_count integer NOT NULL DEFAULT 0,
    enough_count integer NOT NULL DEFAULT 0,
    uhoh_count integer NOT NULL DEFAULT 0,
    poor_count integer NOT NULL DEFAULT 0,
    miss_count integer NOT NULL DEFAULT 0,
    best_combo integer NOT NULL DEFAULT 0,
    loop_reached integer NOT NULL DEFAULT 1,
    lives integer NOT NULL,
    finished_at timestamp(6),
    invalid_reason varchar(32)
);
CREATE INDEX idx_rhythm_challenge_ranking
    ON rhythm_challenge(level, rules_version, member_id, score DESC, finished_at, id)
    WHERE status = 'FINISHED';

CREATE TABLE rhythm_challenge_batch (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    challenge_id bigint NOT NULL REFERENCES rhythm_challenge(id),
    sequence integer NOT NULL CHECK (sequence > 0),
    played_until double precision NOT NULL,
    inputs text NOT NULL,
    UNIQUE (challenge_id, sequence)
);
