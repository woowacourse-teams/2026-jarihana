CREATE TABLE point_wallet (
    member_id bigint PRIMARY KEY REFERENCES member(id),
    balance bigint NOT NULL DEFAULT 0 CHECK (balance BETWEEN 0 AND 9007199254740991)
);

CREATE TABLE point_group_origin (
    group_id bigint PRIMARY KEY,
    creator_member_id bigint NOT NULL,
    created_at timestamp(6) NOT NULL
);

CREATE TABLE point_reward (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES point_wallet(member_id),
    reason varchar(30) NOT NULL CONSTRAINT ck_point_reward_reason_format CHECK (reason ~ '^[A-Z][A-Z0-9_]{0,29}$'),
    source_key varchar(80) NOT NULL,
    scope_key varchar(80),
    policy_version integer NOT NULL CHECK (policy_version > 0),
    amount bigint NOT NULL CHECK (amount > 0),
    occurred_at timestamp(6) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'SKIPPED', 'NEEDS_REVIEW')),
    skip_reason varchar(24),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at timestamp(6) NOT NULL,
    completed_at timestamp(6),
    UNIQUE (member_id, reason, source_key),
    CHECK ((status = 'SKIPPED') = (skip_reason IS NOT NULL)),
    CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL))
);

CREATE UNIQUE INDEX uq_point_reward_once ON point_reward(member_id, reason)
    WHERE reason IN ('GROUP_FIRST_MEMBER', 'FIRST_GROUP_JOIN') AND status <> 'SKIPPED';
CREATE UNIQUE INDEX uq_point_reward_scope ON point_reward(member_id, reason, scope_key)
    WHERE scope_key IS NOT NULL AND status <> 'SKIPPED';
CREATE INDEX idx_point_reward_history ON point_reward(member_id, occurred_at DESC, id DESC);
CREATE INDEX idx_point_reward_quota ON point_reward(member_id, reason, occurred_at)
    WHERE status <> 'SKIPPED';
CREATE INDEX idx_point_reward_due ON point_reward(next_attempt_at, id) WHERE status = 'PENDING';

CREATE TABLE point_ledger (
    reward_id bigint PRIMARY KEY REFERENCES point_reward(id),
    member_id bigint NOT NULL REFERENCES point_wallet(member_id),
    amount bigint NOT NULL CHECK (amount > 0),
    created_at timestamp(6) NOT NULL
);
