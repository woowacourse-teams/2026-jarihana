CREATE TABLE group_music (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL UNIQUE REFERENCES groups(id) ON DELETE CASCADE,
    music_json TEXT NOT NULL,
    revision BIGINT NOT NULL CHECK (revision > 0),
    playback_state VARCHAR(10) NOT NULL CHECK (playback_state IN ('PLAYING', 'PAUSED')),
    playlist_index INTEGER NOT NULL CHECK (playlist_index >= 0),
    position_seconds DOUBLE PRECISION NOT NULL CHECK (position_seconds >= 0),
    anchor_time TIMESTAMP WITH TIME ZONE NOT NULL,
    playback_revision BIGINT NOT NULL CHECK (playback_revision >= 0),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
