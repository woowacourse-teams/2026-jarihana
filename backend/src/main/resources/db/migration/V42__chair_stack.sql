CREATE TABLE chair_stack_player (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT UNIQUE REFERENCES member(id) ON DELETE CASCADE,
    guest_digest CHAR(64) UNIQUE,
    nickname VARCHAR(12) NOT NULL,
    run_id UUID NOT NULL UNIQUE,
    start_request_id UUID NOT NULL,
    last_drop_id UUID,
    positions TEXT NOT NULL DEFAULT '',
    toy_poses TEXT,
    physics_poses TEXT,
    physics_profile SMALLINT NOT NULL DEFAULT 9 CHECK (physics_profile IN (1, 2, 3, 4, 5, 6, 7, 8, 9)),
    stress INTEGER NOT NULL DEFAULT 0 CHECK (stress BETWEEN 0 AND 300),
    failed_layer INTEGER CHECK (failed_layer BETWEEN 1 AND 100),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    best_nickname VARCHAR(12),
    best_score INTEGER NOT NULL DEFAULT 0 CHECK (best_score BETWEEN 0 AND 100),
    best_at TIMESTAMP WITH TIME ZONE,
    CHECK ((member_id IS NULL) <> (guest_digest IS NULL)),
    CHECK ((best_score > 0 AND best_at IS NOT NULL AND best_nickname IS NOT NULL)
        OR (best_score = 0 AND best_at IS NULL AND best_nickname IS NULL))
);

CREATE INDEX idx_chair_stack_ranking
    ON chair_stack_player (best_score DESC, best_at, id)
    WHERE best_score > 0;
