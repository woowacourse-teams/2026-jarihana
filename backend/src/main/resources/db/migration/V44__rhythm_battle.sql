-- 행성이의 리듬 작살 1:1 대전. 신규 테이블만 추가하고 기존 테이블과 랭킹 도전 기록은 바꾸지 않는다.
CREATE TABLE rhythm_battle_room (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    host_member_id bigint NOT NULL REFERENCES member(id),
    host_name varchar(50) NOT NULL,
    guest_member_id bigint REFERENCES member(id),
    guest_name varchar(50),
    visibility varchar(16) NOT NULL CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    level varchar(16) NOT NULL
        CHECK (level IN ('EASY', 'MEDIUM', 'HARD', 'HARDEST', 'ANOTHER_HARD', 'ANOTHER_HARDEST')),
    status varchar(16) NOT NULL CHECK (status IN ('WAITING', 'PLAYING', 'FINISHED', 'CLOSED')),
    host_ready boolean NOT NULL,
    guest_ready boolean NOT NULL,
    host_scroll_speed double precision NOT NULL CHECK (host_scroll_speed >= 1 AND host_scroll_speed <= 3),
    guest_scroll_speed double precision NOT NULL CHECK (guest_scroll_speed >= 1 AND guest_scroll_speed <= 3),
    game_number integer NOT NULL CHECK (game_number >= 0),
    seed integer NOT NULL,
    starts_at timestamp(6),
    winner_member_id bigint REFERENCES member(id),
    end_reason varchar(16) CHECK (end_reason IN ('ELIMINATED', 'FORFEIT', 'DRAW')),
    revision bigint NOT NULL CHECK (revision > 0),
    touched_at timestamp(6) NOT NULL,
    invite_hash varchar(64),
    CHECK (guest_member_id IS NULL OR guest_member_id <> host_member_id)
);
CREATE INDEX idx_rhythm_battle_lobby ON rhythm_battle_room(created_at DESC, id DESC)
    WHERE status = 'WAITING' AND visibility = 'PUBLIC';
CREATE INDEX idx_rhythm_battle_idle ON rhythm_battle_room(touched_at) WHERE status IN ('WAITING', 'FINISHED');
CREATE INDEX idx_rhythm_battle_invite ON rhythm_battle_room(invite_hash) WHERE invite_hash IS NOT NULL;

-- 회원이 지금 앉은 방이다. 나가거나 방이 닫히면 지우고 방 기록은 남긴다.
CREATE TABLE rhythm_battle_seat (
    member_id bigint PRIMARY KEY REFERENCES member(id),
    room_id bigint NOT NULL REFERENCES rhythm_battle_room(id),
    chat_after_id bigint NOT NULL
);
CREATE INDEX idx_rhythm_battle_seat_room ON rhythm_battle_seat(room_id);

-- 한 판에서 한 사람이 친 판이다. 서버가 입력 묶음으로 다시 계산한 결과를 남긴다.
CREATE TABLE rhythm_battle_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    room_id bigint NOT NULL REFERENCES rhythm_battle_room(id),
    game_number integer NOT NULL CHECK (game_number > 0),
    member_id bigint NOT NULL REFERENCES member(id),
    level varchar(16) NOT NULL
        CHECK (level IN ('EASY', 'MEDIUM', 'HARD', 'HARDEST', 'ANOTHER_HARD', 'ANOTHER_HARDEST')),
    scroll_speed double precision NOT NULL CHECK (scroll_speed >= 1 AND scroll_speed <= 3),
    seed integer NOT NULL,
    rules_version varchar(40) NOT NULL,
    chart_version varchar(40) NOT NULL,
    status varchar(16) NOT NULL CHECK (status IN ('PLAYING', 'OUT')),
    starts_at timestamp(6) NOT NULL,
    last_batch_at timestamp(6) NOT NULL,
    last_sequence integer NOT NULL CHECK (last_sequence >= 0),
    played_until double precision NOT NULL,
    last_input_at double precision,
    score bigint NOT NULL,
    combo integer NOT NULL,
    best_combo integer NOT NULL,
    perfect_count integer NOT NULL,
    hit_count integer NOT NULL,
    enough_count integer NOT NULL,
    uhoh_count integer NOT NULL,
    poor_count integer NOT NULL,
    miss_count integer NOT NULL,
    loop_reached integer NOT NULL,
    lives integer NOT NULL,
    out_reason varchar(16) CHECK (out_reason IN ('ELIMINATED', 'ABANDONED', 'STALE', 'LAGGED', 'CLOCK_AHEAD')),
    out_at double precision,
    ended_at timestamp(6),
    UNIQUE (room_id, game_number, member_id),
    CHECK ((status = 'PLAYING' AND out_reason IS NULL AND out_at IS NULL AND ended_at IS NULL)
        OR (status = 'OUT' AND out_reason IS NOT NULL AND out_at IS NOT NULL AND ended_at IS NOT NULL))
);
CREATE INDEX idx_rhythm_battle_run_stale ON rhythm_battle_run(last_batch_at) WHERE status = 'PLAYING';

CREATE TABLE rhythm_battle_batch (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    run_id bigint NOT NULL REFERENCES rhythm_battle_run(id),
    sequence integer NOT NULL CHECK (sequence > 0),
    played_until double precision NOT NULL,
    inputs text NOT NULL,
    UNIQUE (run_id, sequence)
);

-- 시작한 판의 기록이다. 다시 대결하거나 방이 닫혀도 바꾸지 않는다.
CREATE TABLE rhythm_battle_game (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    room_id bigint NOT NULL REFERENCES rhythm_battle_room(id),
    game_number integer NOT NULL CHECK (game_number > 0),
    host_member_id bigint NOT NULL REFERENCES member(id),
    guest_member_id bigint NOT NULL REFERENCES member(id),
    host_name varchar(50) NOT NULL,
    guest_name varchar(50) NOT NULL,
    level varchar(16) NOT NULL
        CHECK (level IN ('EASY', 'MEDIUM', 'HARD', 'HARDEST', 'ANOTHER_HARD', 'ANOTHER_HARDEST')),
    winner_member_id bigint REFERENCES member(id),
    end_reason varchar(16) CHECK (end_reason IN ('ELIMINATED', 'FORFEIT', 'DRAW')),
    ended_at timestamp(6),
    UNIQUE (room_id, game_number),
    CHECK (host_member_id <> guest_member_id),
    CHECK (winner_member_id IS NULL OR winner_member_id IN (host_member_id, guest_member_id)),
    CHECK ((ended_at IS NULL AND end_reason IS NULL AND winner_member_id IS NULL)
        OR (ended_at IS NOT NULL AND end_reason IS NOT NULL
            AND ((end_reason = 'DRAW' AND winner_member_id IS NULL)
                OR (end_reason <> 'DRAW' AND winner_member_id IS NOT NULL))))
);
CREATE INDEX idx_rhythm_battle_game_host ON rhythm_battle_game(host_member_id) WHERE ended_at IS NOT NULL;
CREATE INDEX idx_rhythm_battle_game_guest ON rhythm_battle_game(guest_member_id) WHERE ended_at IS NOT NULL;

-- 방 채팅이다. 방이 닫히면 지운다.
CREATE TABLE rhythm_battle_chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    room_id bigint NOT NULL REFERENCES rhythm_battle_room(id),
    member_id bigint NOT NULL REFERENCES member(id),
    sender_name varchar(50) NOT NULL,
    body varchar(300) NOT NULL,
    client_message_id uuid NOT NULL,
    UNIQUE (room_id, member_id, client_message_id)
);
CREATE INDEX idx_rhythm_battle_chat_room ON rhythm_battle_chat_message(room_id, id);
