-- Refresh Token 회전과 재사용 감지. 로그인 하나를 패밀리로 묶고, 폐기와 절대 만료는 패밀리 단위로 관리한다.
-- 회전을 모르는 이전 버전이 같은 DB를 함께 쓰므로 refresh_token에는 nullable 컬럼만 더한다(Expand).
-- 이전 버전이 만든 행은 refresh_token_family_id가 비어 있고, 새 버전이 처음 회전할 때 패밀리에 넣는다.
CREATE TABLE refresh_token_family (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    member_id bigint NOT NULL REFERENCES member(id),
    absolute_expires_at timestamp(6) NOT NULL,
    revoked_at timestamp(6),
    revoke_reason varchar(20) CHECK (revoke_reason IN ('REUSE_DETECTED', 'LOGOUT')),
    CHECK ((revoked_at IS NULL) = (revoke_reason IS NULL))
);

ALTER TABLE refresh_token
    ADD COLUMN refresh_token_family_id bigint REFERENCES refresh_token_family(id),
    ADD COLUMN rotated_at timestamp(6);

CREATE INDEX idx_refresh_token_family ON refresh_token(refresh_token_family_id);
