-- 소속과 회원의 소속 인증. 모임장은 자신이 인증된 소속의 회원에게만 모임을 공개할 수 있다.
-- 소속은 서비스가 확인한 방법으로만 회원에게 붙는다. 지금은 우아한테크코스 하나이고 크루 명단(crew_roster)으로 확인한다.
-- 자가 입력 소속(bootcamp_name, company_name)은 확인하지 않은 값이라 여기에 옮기지 않는다.
SET LOCAL lock_timeout = '5s';

CREATE TABLE affiliation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(30) NOT NULL,
    name character varying(50) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL DEFAULT localtimestamp,
    updated_at timestamp(6) without time zone NOT NULL DEFAULT localtimestamp,
    CONSTRAINT uk_affiliation_code UNIQUE (code)
);

CREATE TABLE member_affiliation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    affiliation_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL DEFAULT localtimestamp,
    updated_at timestamp(6) without time zone NOT NULL DEFAULT localtimestamp,
    CONSTRAINT uk_member_affiliation UNIQUE (member_id, affiliation_id),
    CONSTRAINT fk_member_affiliation_member FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT fk_member_affiliation_affiliation FOREIGN KEY (affiliation_id) REFERENCES affiliation (id)
);

INSERT INTO affiliation (code, name)
VALUES ('WOOTECO', '우아한테크코스');

-- 크루 명단에 있는 크루를 우아한테크코스 소속으로 옮긴다. 명단 인증 전부터 있던 자가 신고 크루는 명단에 있을 때만,
-- 코치는 명단으로 확인하지 않으므로 넣지 않는다.
-- 이 마이그레이션 뒤 이전 버전이 크루로 바꾼 회원은 다음 GitHub 로그인이나 명단 적재에서 소속이 채워진다.
INSERT INTO member_affiliation (member_id, affiliation_id)
SELECT m.id, a.id
FROM member m
         JOIN affiliation a ON a.code = 'WOOTECO'
WHERE m.member_type = 'CREW'
  AND EXISTS (SELECT 1 FROM crew_roster r WHERE r.github_id = m.github_id);
