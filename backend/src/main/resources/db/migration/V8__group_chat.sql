CREATE TABLE chat_room (
    group_id bigint PRIMARY KEY REFERENCES groups(id) ON DELETE CASCADE,
    last_sequence bigint NOT NULL DEFAULT 0 CHECK (last_sequence >= 0)
);
CREATE TABLE chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    sequence bigint NOT NULL CHECK (sequence > 0),
    sender_id bigint NOT NULL REFERENCES member(id),
    client_message_id uuid NOT NULL,
    content text NOT NULL CHECK (char_length(content) BETWEEN 1 AND 2000),
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uq_chat_message_sequence UNIQUE (group_id, sequence),
    CONSTRAINT uq_chat_message_request UNIQUE (group_id, sender_id, client_message_id)
);
CREATE TABLE chat_read_state (
    group_id bigint NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    member_id bigint NOT NULL REFERENCES member(id),
    last_read_sequence bigint NOT NULL DEFAULT 0 CHECK (last_read_sequence >= 0),
    PRIMARY KEY (group_id, member_id)
);
CREATE INDEX idx_chat_read_member ON chat_read_state(member_id, group_id);
