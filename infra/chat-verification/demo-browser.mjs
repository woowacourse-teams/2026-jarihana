import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { randomUUID } from "node:crypto";
import { mkdir } from "node:fs/promises";
import { createDemoAccounts } from "./demo-accounts.mjs";

const require = createRequire(new URL("../../frontend/package.json", import.meta.url));
const { chromium, expect } = require("playwright/test");
const { default: AxeBuilder } = require("@axe-core/playwright");
const output = "/private/tmp/jarihana-chat-realtime/evidence";
const origin = "http://localhost:5176";
await mkdir(output, { recursive: true });
assert.equal(createDemoAccounts({ enabled: false }), null);
assert.throws(() => createDemoAccounts({ enabled: true, secret: "x".repeat(32), databaseUrl: "jdbc:postgresql://production/db", port: 5176 }));
const browser = await chromium.launch({ headless: true });
try {
  const first = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const second = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const a = await first.newPage(), b = await second.newPage();
  const errors = [];
  for (const page of [a, b]) page.on("pageerror", (error) => errors.push(error.message));
  await a.goto(`${origin}/_preview/chat`);
  const accessibility = await new AxeBuilder({ page: a }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  assert.deepEqual(accessibility.violations.map((v) => v.id), []);
  await a.screenshot({ path: `${output}/chat-demo-accounts.png` });
  await a.setViewportSize({ width: 360, height: 900 });
  assert.ok(await a.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await a.getByRole("button", { name: /하루로 시작하기/ }).click();
  await expect(a.getByLabel("메시지", { exact: true })).toBeVisible();
  await b.goto(`${origin}/_preview/chat`);
  await b.getByRole("button", { name: /모아로 시작하기/ }).click();
  await expect(b.getByLabel("메시지", { exact: true })).toBeVisible();
  for (const [context, name] of [[first, "하루"], [second, "모아"]]) {
    const me = await context.request.get(`${origin}/api/members/me`);
    assert.equal(me.status(), 200);
    assert.equal((await me.json()).data.member.crewName, name);
    const rooms = await context.request.get(`${origin}/api/chats`);
    const items = (await rooms.json()).data.items;
    assert.equal(items.length, 3);
    assert.ok(items.every((room) => typeof room.representativeImageUrl === "string"));
    assert.deepEqual(items.map((room) => room.groupId).sort(), ["905001", "905002", "905003"]);
  }
  console.log("PASS two demo accounts authenticate with the real backend and belong to exactly three rooms");
  const text = `직접 테스트 ${randomUUID()}`;
  await a.getByLabel("메시지", { exact: true }).fill(text);
  await a.getByLabel("메시지", { exact: true }).press("Enter");
  await expect(b.locator(".chat-message__bubble", { hasText: text })).toBeVisible();
  const reply = `답장 ${randomUUID()}`;
  await b.getByLabel("메시지", { exact: true }).fill(reply);
  await b.getByLabel("메시지", { exact: true }).press("Enter");
  await expect(a.locator(".chat-message__bubble", { hasText: reply })).toBeVisible();
  await a.reload();
  await expect(a.locator(".chat-message__bubble", { hasText: reply })).toBeVisible();
  await a.getByRole("link", { name: "채팅 목록으로" }).click();
  await a.locator('[data-room-id="905003"]').click();
  await expect(a.getByText("종료된 모임이에요. 나눴던 이야기는 계속 볼 수 있어요.")).toBeVisible();
  assert.equal(await a.getByLabel("메시지", { exact: true }).count(), 0);
  console.log("PASS two-way real-time messaging, saved history after reload and read-only ended room");

  const landing = await first.request.get(`${origin}/_preview/chat`);
  const csrf = (await landing.text()).match(/name="csrf" value="([^"]+)"/)[1];
  const deniedOrigin = await first.request.post(`${origin}/_preview/login`, { headers: { Origin: "https://example.com" }, form: { csrf, account: "haru" }, maxRedirects: 0 });
  assert.equal(deniedOrigin.status(), 403);
  const missing = await first.request.post(`${origin}/_preview/login`, { headers: { Origin: origin }, form: { account: "haru" }, maxRedirects: 0 });
  assert.equal(missing.status(), 403);
  const arbitrary = await first.request.post(`${origin}/_preview/login`, { headers: { Origin: origin }, form: { csrf, account: "1" }, maxRedirects: 0 });
  assert.equal(arbitrary.status(), 400);
  const wrongHost = await first.request.get("http://127.0.0.1:5176/_preview/chat");
  assert.equal(wrongHost.status(), 400);
  const disabled = await first.request.get("http://localhost:8080/_preview/chat");
  assert.equal(disabled.status(), 404);
  assert.deepEqual(errors, []);
  console.log("PASS local-only opt-in, isolated DB guard, host, CSRF, origin and fixed-account restrictions; zero page errors");
} finally { await browser.close(); }
