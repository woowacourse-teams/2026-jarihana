import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import { user } from "./verify.mjs";

const require = createRequire(new URL("../../frontend/package.json", import.meta.url));
const { chromium, expect } = require("playwright/test");
const { default: AxeBuilder } = require("@axe-core/playwright");
const output = process.env.CHAT_EVIDENCE_DIR ?? "/private/tmp/jarihana-chat-realtime/evidence";
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: "ko-KR", timezoneId: "Asia/Seoul" });
  const account = user(901001);
  await context.addCookies([
    { name: "accessToken", value: account.accessToken, domain: "127.0.0.1", path: "/", httpOnly: true, sameSite: "Lax" },
    { name: "XSRF-TOKEN", value: account.csrf, domain: "127.0.0.1", path: "/", sameSite: "Lax" }
  ]);
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("http://127.0.0.1:5176/groups?type=STUDY");
  const opener = page.locator('.app-header__chat:visible').first();
  await opener.waitFor();
  await page.waitForLoadState("networkidle");
  await page.locator("main").evaluate((node) => { node.dataset.chatBackgroundProbe = "same-page"; });
  await page.evaluate(() => window.scrollTo({ top: 180, behavior: "instant" }));
  const scroll = await page.evaluate(() => window.scrollY);
  const before = new URL(page.url());
  const openerBox = await opener.boundingBox();
  await page.mouse.click(openerBox.x + openerBox.width / 2, openerBox.y + openerBox.height / 2);
  const modal = page.getByRole("dialog", { name: "모임 채팅", exact: true });
  await expect(modal).toBeVisible();
  await expect(page.locator('.chat-room-row').first()).toBeVisible();
  assert.equal(await page.locator("main").getAttribute("data-chat-background-probe"), "same-page");
  assert.equal(new URL(page.url()).searchParams.get("type"), "STUDY");
  assert.equal(await page.evaluate(() => window.scrollY), scroll);
  assert.equal(await page.evaluate(() => document.body.style.overflow), "hidden");
  await page.locator('[data-room-id="902002"]').click();
  await expect(page.getByLabel("메시지", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "모임 정보", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "모임 정보", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog", { name: "모임 정보", exact: true })).toHaveCount(0);
  await expect(modal).toBeVisible();
  await expect(page.getByRole("button", { name: "모임 정보", exact: true })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(modal).toHaveCount(0);
  assert.equal(page.url(), before.href);
  assert.equal(await page.evaluate(() => window.scrollY), scroll);
  await expect(opener).toBeFocused();
  console.log("PASS current page, query, scroll and opener focus survive modal; nested Escape closes one overlay");

  await opener.click();
  await page.locator('[data-room-id="902002"]').click();
  await page.goBack();
  await expect(modal).toHaveCount(0);
  assert.equal(page.url(), before.href);
  await opener.click();
  await page.locator('[data-room-id="902002"]').click();
  for (const width of [1440, 768, 360]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect(page.getByLabel("메시지", { exact: true })).toBeVisible();
    const box = await modal.boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= width + 1);
    assert.ok(box.y >= 0 && box.y + box.height <= 1001);
    if (width < 768) assert.equal(box.width, width);
    else assert.ok(box.width < width && box.height < 1000, "desktop shows the backdrop");
    await page.screenshot({ path: `${output}/chat-modal-${width}.png` });
    const a11y = await new AxeBuilder({ page }).include(".chat-modal").withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
    assert.deepEqual(a11y.violations.map((v) => ({ id: v.id, nodes: v.nodes.map((n) => n.target) })), []);
  }
  await page.getByRole("button", { name: "채팅 닫기" }).focus();
  await page.keyboard.press("Tab");
  await expect(page.getByRole("link", { name: "채팅 목록으로" })).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(page.getByRole("button", { name: "채팅 닫기" })).toBeFocused();
  await page.getByRole("link", { name: "채팅 목록으로" }).click();
  await expect(page.locator(".chat-sidebar")).toBeVisible();
  await expect(page.locator('[data-room-id="902002"]')).toBeFocused();
  await page.getByRole("button", { name: "채팅 닫기" }).click();
  await expect(modal).toHaveCount(0);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await opener.click();
  await page.mouse.click(4, 4);
  await expect(modal).toHaveCount(0);
  await page.goto("http://127.0.0.1:5176/chat/902002");
  await expect(modal).toBeVisible();
  await expect(page.getByLabel("메시지", { exact: true })).toBeVisible();
  assert.equal(new URL(page.url()).pathname, "/home");
  assert.equal(new URL(page.url()).searchParams.get("chat"), "902002");
  await page.getByRole("button", { name: "모임 정보", exact: true }).click();
  await page.getByRole("link", { name: "모임 보러 가기" }).click();
  await expect(modal).toHaveCount(0);
  assert.equal(await page.evaluate(() => document.body.style.overflow), "");
  await page.locator('[data-ph-capture-attribute-action="group_chat_open"]').click();
  await expect(page.getByLabel("메시지", { exact: true })).toBeVisible();
  assert.equal(new URL(page.url()).pathname, "/groups/902002");
  await page.getByRole("button", { name: "채팅 닫기" }).click();
  await page.setViewportSize({ width: 360, height: 1000 });
  await page.getByRole("button", { name: "메뉴 열기" }).click();
  await page.getByRole("dialog", { name: "전체 메뉴" }).getByRole("link", { name: "채팅", exact: true }).click();
  await expect(modal).toBeVisible();
  await expect(page.getByRole("button", { name: "채팅 닫기" })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(modal).toHaveCount(0);
  assert.equal(await page.evaluate(() => document.body.style.overflow), "");
  assert.deepEqual(errors, []);
  console.log("PASS back navigation, backdrop dismiss, desktop/mobile sizing, visible keyboard focus, legacy link and accessibility");
  console.log("PASS nested group navigation unlocks scroll; group shortcut and mobile menu open the modal");
} finally { await browser.close(); }
